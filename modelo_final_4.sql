-- SCRIPT GENERADO PARA ORACLE SQL DATA MODELER
-- MODELO FINAL SAGUARO v4 (Con CONSTRAINTS INLINE garantizados para Data Modeler)

-- 1. USUARIOS Y ROLES
CREATE TABLE ROL (
    id_rol NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR2(50) UNIQUE NOT NULL,
    descripcion CLOB
);

CREATE TABLE PERMISO (
    id_permiso NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_permiso VARCHAR2(100) UNIQUE NOT NULL,
    descripcion CLOB
);

CREATE TABLE ROL_PERMISO (
    id_rol NUMBER NOT NULL REFERENCES ROL(id_rol),
    id_permiso NUMBER NOT NULL REFERENCES PERMISO(id_permiso),
    CONSTRAINT pk_rol_permiso PRIMARY KEY (id_rol, id_permiso)
);

CREATE TABLE USUARIO (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol NUMBER REFERENCES ROL(id_rol),
    nombres VARCHAR2(100) NOT NULL,
    primer_apellido VARCHAR2(100) NOT NULL,
    segundo_apellido VARCHAR2(100) NOT NULL,
    rut VARCHAR2(12) UNIQUE NOT NULL,
    telefono VARCHAR2(20) NOT NULL,
    direccion_email VARCHAR2(100) UNIQUE NOT NULL,
    genero VARCHAR2(20) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_ultima_actualizacion TIMESTAMP,
    estado NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE USUARIO_LOGIN (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER UNIQUE NOT NULL REFERENCES USUARIO(id_usuario),
    hash_contrasena VARCHAR2(255) NOT NULL,
    bloqueado NUMBER(1) DEFAULT 0 NOT NULL,
    fecha_conexion TIMESTAMP
);

CREATE TABLE HISTORIAL_INTENTOS_LOGIN (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
    fecha_intento TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. DIRECCIONES
CREATE TABLE REGION (
    id_region NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    codigo VARCHAR2(10) NOT NULL
);

CREATE TABLE COMUNA (
    id_comuna NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_region NUMBER NOT NULL REFERENCES REGION(id_region),
    nombre VARCHAR2(100) NOT NULL
);

CREATE TABLE DIRECCION (
    id_usuario NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
    id_comuna NUMBER NOT NULL REFERENCES COMUNA(id_comuna),
    id_direccion NUMBER NOT NULL,
    calle VARCHAR2(100) NOT NULL,
    numero VARCHAR2(20),
    departamento VARCHAR2(20),
    detalles VARCHAR2(255),
    activa NUMBER(1) DEFAULT 1 NOT NULL,
    es_principal NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_direccion PRIMARY KEY (id_usuario, id_comuna, id_direccion)
);

-- 3. PRODUCTOS Y CATEGORIAS
CREATE TABLE CATEGORIA (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR2(100) NOT NULL,
    descripcion CLOB
);

CREATE TABLE MODELO (
    id_modelo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria NUMBER NOT NULL REFERENCES CATEGORIA(id_categoria),
    nombre_modelo VARCHAR2(100) NOT NULL,
    descripcion CLOB NOT NULL,
    marca VARCHAR2(100) NOT NULL
);

CREATE TABLE COLOR (
    id_color NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_color VARCHAR2(50) NOT NULL,
    codigo_hex VARCHAR2(7) NOT NULL
);

CREATE TABLE TALLA (
    id_talla NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_talla VARCHAR2(50) NOT NULL
);

CREATE TABLE PROVEEDOR (
    id_proveedor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    contacto VARCHAR2(100),
    telefono VARCHAR2(20),
    email VARCHAR2(100)
);

CREATE TABLE PRODUCTO (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo NUMBER NOT NULL REFERENCES MODELO(id_modelo),
    id_color NUMBER NOT NULL REFERENCES COLOR(id_color),
    id_talla NUMBER NOT NULL REFERENCES TALLA(id_talla),
    id_proveedor NUMBER REFERENCES PROVEEDOR(id_proveedor),
    codigo_sku VARCHAR2(50) UNIQUE NOT NULL,
    precio NUMBER(10,2) NOT NULL,
    stock NUMBER NOT NULL,
    fecha_ingreso DATE DEFAULT CURRENT_DATE NOT NULL
);

-- 4. LOGISTICA Y VENTAS
CREATE TABLE HISTORIAL_PRECIOS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    precio_anterior NUMBER(10,2) NOT NULL,
    precio_nuevo NUMBER(10,2) NOT NULL,
    fecha_cambio TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE PRODUCTO_NOVEDAD (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL
);

CREATE TABLE PROMOCION (
    id_promocion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    porcentaje_descuento NUMBER NOT NULL,
    fecha_ini TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL
);

CREATE TABLE PRODUCTO_PROMOCION (
    id_producto_promocion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    id_promocion NUMBER NOT NULL REFERENCES PROMOCION(id_promocion),
    descuento_especifico NUMBER,
    activo NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE ARTICULO_CARRITO_COMPRA (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    cantidad NUMBER NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL
);

CREATE TABLE PEDIDO (
    id_pedido NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
    fk_usuario_dir NUMBER NOT NULL,
    id_comuna_dir NUMBER NOT NULL,
    fk_correlativo_dir NUMBER NOT NULL,
    estado VARCHAR2(50) DEFAULT 'pendiente' NOT NULL,
    fecha_pedido TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    total NUMBER(12,2) NOT NULL,
    comentarios CLOB,
    CONSTRAINT fk_ped_direccion FOREIGN KEY (fk_usuario_dir, id_comuna_dir, fk_correlativo_dir) REFERENCES DIRECCION (id_usuario, id_comuna, id_direccion)
);

CREATE TABLE ARTICULO_PEDIDO (
    id_pedido NUMBER NOT NULL REFERENCES PEDIDO(id_pedido),
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    cantidad NUMBER NOT NULL,
    precio NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_articulo_pedido PRIMARY KEY (id_pedido, id_producto)
);

CREATE TABLE METODO_PAGO (
    id_metodo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    descripcion VARCHAR2(255)
);

CREATE TABLE TRANSACCION_PAGO (
    id_transaccion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL REFERENCES PEDIDO(id_pedido),
    id_metodo NUMBER NOT NULL REFERENCES METODO_PAGO(id_metodo),
    monto NUMBER(12,2) NOT NULL,
    fecha_pago TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado_pago VARCHAR2(50) NOT NULL,
    token_ws VARCHAR2(255),
    cod_autorizacion VARCHAR2(50)
);

CREATE TABLE EMPRESA_TRANSPORTE (
    id_empresa NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    email VARCHAR2(100),
    telefono NUMBER,
    direccion VARCHAR2(255)
);

CREATE TABLE ENVIO (
    id_envio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL REFERENCES PEDIDO(id_pedido),
    id_usuario_dir NUMBER NOT NULL,
    id_comuna_dir NUMBER NOT NULL,
    id_dir_dir NUMBER NOT NULL,
    id_empresa NUMBER NOT NULL REFERENCES EMPRESA_TRANSPORTE(id_empresa),
    numero_seguimiento VARCHAR2(100) NOT NULL,
    fecha_envio TIMESTAMP NOT NULL,
    fecha_entrega_estimada TIMESTAMP
);

CREATE TABLE DEVOLUCION (
    id_devolucion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido NUMBER NOT NULL REFERENCES PEDIDO(id_pedido),
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    motivo VARCHAR2(255) NOT NULL,
    estado_devolucion VARCHAR2(50) NOT NULL,
    fecha_solicitud TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_procesada TIMESTAMP
);

CREATE TABLE VALORACION (
    id_valoracion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    puntuacion NUMBER NOT NULL,
    comentario CLOB,
    sentimiento VARCHAR2(50),
    score_sentimiento NUMBER(10,2) NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE SOLICITUD_CONTACTO (
    id_solicitud NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER REFERENCES USUARIO(id_usuario),
    nombre_remitente VARCHAR2(100) NOT NULL,
    correo_remitente VARCHAR2(100) NOT NULL,
    mensaje CLOB NOT NULL,
    fecha_envio TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    estado NUMBER(1) DEFAULT 0 NOT NULL
);

-- 9. TABLAS EXTRA (COMPATIBILIDAD)
CREATE TABLE LISTA_DESEOS (
    id_wishlist NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
    id_producto NUMBER NOT NULL REFERENCES PRODUCTO(id_producto),
    fecha_agregado TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_lista_deseos UNIQUE (id_usuario, id_producto)
);


